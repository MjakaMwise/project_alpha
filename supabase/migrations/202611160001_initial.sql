-- Central database schema for the Customize Rust backend.
-- Apply with a database-owner connection, never from browser code.
BEGIN;
CREATE SCHEMA IF NOT EXISTS customize;
REVOKE ALL ON SCHEMA customize FROM PUBLIC, anon, authenticated;
SET LOCAL search_path TO customize;

CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE CHECK (email = lower(email)),
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('shopper', 'shop_owner', 'admin')),
    created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS shops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL DEFAULT '',
    owner_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
    created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS products (
    id TEXT PRIMARY KEY,
    shop_id BIGINT NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    position BIGINT NOT NULL,
    name TEXT NOT NULL,
    type TEXT NOT NULL,
    vessel TEXT NOT NULL,
    description TEXT NOT NULL,
    price BIGINT NOT NULL,
    height_cm BIGINT NOT NULL,
    size TEXT NOT NULL,
    light TEXT NOT NULL,
    tags TEXT NOT NULL,
    scale DOUBLE PRECISION NOT NULL,
    image TEXT
);
CREATE TABLE IF NOT EXISTS shoppers (id TEXT PRIMARY KEY, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ref TEXT NOT NULL,
    shopper_key TEXT NOT NULL,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    customer_name TEXT NOT NULL DEFAULT '',
    phone TEXT NOT NULL DEFAULT '',
    address TEXT NOT NULL DEFAULT '',
    note TEXT NOT NULL DEFAULT '',
    total BIGINT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('placed', 'confirmed', 'preparing', 'out_for_delivery', 'delivered', 'cancelled')),
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    UNIQUE (shopper_key, ref)
);
CREATE INDEX IF NOT EXISTS orders_status ON orders (status, created_at);
CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id TEXT NOT NULL,
    name TEXT NOT NULL,
    shop_id BIGINT,
    shop_name TEXT NOT NULL DEFAULT '',
    price BIGINT NOT NULL,
    quantity BIGINT NOT NULL,
    image TEXT
);
CREATE TABLE IF NOT EXISTS order_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    status TEXT NOT NULL,
    note TEXT NOT NULL DEFAULT '',
    actor TEXT NOT NULL,
    at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user_id ON sessions(user_id);
CREATE INDEX IF NOT EXISTS shops_owner_id ON shops(owner_id);
CREATE INDEX IF NOT EXISTS products_shop_id ON products(shop_id, position);
CREATE INDEX IF NOT EXISTS orders_user_id ON orders(user_id);
CREATE INDEX IF NOT EXISTS order_items_order_id ON order_items(order_id);
CREATE INDEX IF NOT EXISTS order_events_order_id ON order_events(order_id);
-- Backend-only tables: browser API roles have no direct access.
ALTER TABLE customize.meta ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE customize.meta FROM PUBLIC, anon, authenticated;
ALTER TABLE customize.users ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE customize.users FROM PUBLIC, anon, authenticated;
ALTER TABLE customize.sessions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE customize.sessions FROM PUBLIC, anon, authenticated;
ALTER TABLE customize.shops ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE customize.shops FROM PUBLIC, anon, authenticated;
ALTER TABLE customize.products ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE customize.products FROM PUBLIC, anon, authenticated;
ALTER TABLE customize.shoppers ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE customize.shoppers FROM PUBLIC, anon, authenticated;
ALTER TABLE customize.orders ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE customize.orders FROM PUBLIC, anon, authenticated;
ALTER TABLE customize.order_items ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE customize.order_items FROM PUBLIC, anon, authenticated;
ALTER TABLE customize.order_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE customize.order_events FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA customize FROM PUBLIC, anon, authenticated;
COMMIT;
